-- The role-dependent required fields are enforced when a role is assigned.
CREATE FUNCTION enforce_role_required_user_fields() RETURNS trigger
LANGUAGE plpgsql AS $$
DECLARE
  v_code text;
  v_user users%ROWTYPE;
BEGIN
  SELECT * INTO v_user FROM users WHERE id = NEW.user_id;
  SELECT code INTO v_code FROM roles WHERE id = NEW.role_id;
  IF v_code = 'student' AND (v_user.student_number IS NULL OR length(btrim(v_user.student_number)) = 0) THEN
    RAISE EXCEPTION 'student_number is required for student accounts' USING ERRCODE = '23514';
  END IF;
  IF v_code = 'student' AND v_user.specialty_id IS NULL THEN
    RAISE EXCEPTION 'specialty_id is required for student accounts' USING ERRCODE = '23514';
  END IF;
  IF v_code = 'company_representative' AND (v_user.company_name IS NULL OR length(btrim(v_user.company_name)) = 0) THEN
    RAISE EXCEPTION 'company_name is required for company representative accounts' USING ERRCODE = '23514';
  END IF;
  RETURN NEW;
END;
$$;
CREATE TRIGGER user_roles_required_fields_trg
  AFTER INSERT OR UPDATE OF user_id, role_id ON user_roles
  FOR EACH ROW EXECUTE FUNCTION enforce_role_required_user_fields();

CREATE FUNCTION enforce_user_role_scope() RETURNS trigger
LANGUAGE plpgsql AS $$
DECLARE
  v_code text;
  v_user_college_id uuid;
BEGIN
  SELECT code INTO v_code FROM roles WHERE id = NEW.role_id;
  SELECT college_id INTO v_user_college_id FROM users WHERE id = NEW.user_id;
  IF v_code = 'system_admin' THEN
    IF NEW.college_id IS NOT NULL OR v_user_college_id IS NOT NULL THEN
      RAISE EXCEPTION 'system_admin must be a global user with no college scope' USING ERRCODE = '23514';
    END IF;
  ELSIF NEW.college_id IS NULL OR v_user_college_id IS DISTINCT FROM NEW.college_id THEN
    RAISE EXCEPTION 'College role assignment must match the user college_id' USING ERRCODE = '23514';
  END IF;
  RETURN NEW;
END;
$$;
CREATE TRIGGER user_roles_scope_guard_trg
  BEFORE INSERT OR UPDATE OF user_id, role_id, college_id ON user_roles
  FOR EACH ROW EXECUTE FUNCTION enforce_user_role_scope();

CREATE FUNCTION enforce_user_role_fields_on_update() RETURNS trigger
LANGUAGE plpgsql AS $$
BEGIN
  IF EXISTS (
    SELECT 1 FROM user_roles ur JOIN roles r ON r.id = ur.role_id
    WHERE ur.user_id = NEW.id AND r.code = 'student'
      AND (NEW.student_number IS NULL OR length(btrim(NEW.student_number)) = 0 OR NEW.specialty_id IS NULL)
  ) THEN
    RAISE EXCEPTION 'student_number and specialty_id are required for student accounts' USING ERRCODE = '23514';
  END IF;
  IF EXISTS (
    SELECT 1 FROM user_roles ur JOIN roles r ON r.id = ur.role_id
    WHERE ur.user_id = NEW.id AND r.code = 'company_representative'
      AND (NEW.company_name IS NULL OR length(btrim(NEW.company_name)) = 0)
  ) THEN
    RAISE EXCEPTION 'company_name is required for company representative accounts' USING ERRCODE = '23514';
  END IF;
  RETURN NEW;
END;
$$;
CREATE TRIGGER users_required_role_fields_update_trg
  BEFORE UPDATE OF student_number, company_name, specialty_id ON users
  FOR EACH ROW EXECUTE FUNCTION enforce_user_role_fields_on_update();

COMMIT;
